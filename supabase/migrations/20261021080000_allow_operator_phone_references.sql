alter table public.device_model
    add column source text not null default 'catalog'
        check (source in ('catalog', 'operator-added')),
    add column created_by uuid references auth.users(id) on delete set null;

-- Phone specifications are non-sensitive and are needed for anonymous scan
-- comparison; charger models remain private to authenticated operators.
create policy "public can read phone references"
    on public.device_model for select to anon
    using (device_type = 'phone');
grant select (
    model_id,
    brand,
    model_name,
    device_type,
    baseline_weight_g,
    baseline_thickness_mm,
    nominal_current_ma
) on public.device_model to anon;

create policy "authenticated operators can add phone references"
    on public.device_model for insert to authenticated
    with check (
        device_type = 'phone'
        and source = 'operator-added'
        and created_by = (select auth.uid())
    );

grant insert (
    brand,
    model_name,
    device_type,
    baseline_weight_g,
    baseline_thickness_mm,
    nominal_current_ma,
    source,
    created_by
) on public.device_model to authenticated;

create table public.operator_diagnosis (
    diagnosis_id bigint generated by default as identity primary key,
    telemetry_id bigint not null references public.station_telemetry(telemetry_id) on delete cascade,
    operator_id uuid not null references auth.users(id) on delete cascade,
    device_model_id bigint references public.device_model(model_id) on delete set null,
    decision text not null check (decision in ('resellable', 'recycle', 'disposal', 'needs-review')),
    notes text,
    created_at timestamptz not null default now(),
    unique (telemetry_id, operator_id)
);

alter table public.operator_diagnosis enable row level security;
create policy "operators manage their diagnosis reviews"
    on public.operator_diagnosis for all to authenticated
    using (operator_id = (select auth.uid()))
    with check (operator_id = (select auth.uid()));
grant select, insert, update, delete on public.operator_diagnosis to authenticated;
grant usage, select on sequence public.operator_diagnosis_diagnosis_id_seq to authenticated;
